// Regenerates prototype/assets/icons.js (Lucide subset) and prototype/assets/tracks.js (built-in tracks).
// Usage: node docs/design/lab-ui/tools/build-assets.mjs <path to node_modules with lucide-static>
// Node is needed only to regenerate these two files; the prototype itself runs without it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..', '..');
const out = join(here, '..', 'prototype', 'assets');
const modules = process.argv[2];
if (!modules) throw new Error('pass the node_modules directory that contains lucide-static');

// Lucide name -> id used in the prototype (kept equal unless a shorter id reads better).
const ICONS = [
  'flask-conical', 'route', 'trophy', 'warehouse', 'settings', 'play', 'pause', 'square', 'plus',
  'minus', 'x', 'chevron-down', 'chevron-right', 'chevron-left', 'ellipsis', 'copy', 'download',
  'upload', 'trash-2', 'maximize-2', 'crosshair', 'scan', 'zoom-in', 'zoom-out', 'columns-2', 'eye',
  'eye-off', 'info', 'circle-help', 'triangle-alert', 'check', 'star', 'brush', 'eraser', 'hand',
  'flag', 'undo-2', 'redo-2', 'save', 'waves', 'move-horizontal', 'gauge', 'timer', 'network',
  'sliders-horizontal', 'dna', 'brain', 'list-checks', 'volume-2', 'volume-x', 'sun', 'moon',
  'monitor', 'keyboard', 'lock', 'zap', 'activity', 'chart-line', 'table', 'rotate-ccw', 'layers',
  'circle-dot', 'grip-vertical', 'map', 'search', 'pencil', 'lightbulb', 'spline', 'git-compare-arrows',
  'octagon-x', 'circle-check', 'fast-forward', 'file-json', 'flag-triangle-right', 'radar',
  'arrow-right', 'arrow-left', 'skip-back',
];

const symbols = ICONS.map((name) => {
  const svg = readFileSync(join(modules, 'lucide-static', 'icons', `${name}.svg`), 'utf8');
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`;
});

const icons = `/* Generated by tools/build-assets.mjs from lucide-static (ISC licence, see licenses/lucide-ISC.txt). */
(function () {
  var sprite = '<svg aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' +
    ${JSON.stringify(symbols.join(''))} + '</svg>';
  document.body.insertAdjacentHTML('afterbegin', sprite);
})();
`;
writeFileSync(join(out, 'icons.js'), icons);

const tracks = {};
for (const name of ['oval', 'wavy', 'circuit']) {
  const data = JSON.parse(readFileSync(join(root, 'src', 'rl_fun', 'racing', 'tracks', `${name}.json`), 'utf8'));
  tracks[name] = { width: data.width, center: data.centerline };
}
writeFileSync(
  join(out, 'tracks.js'),
  `/* Generated by tools/build-assets.mjs from src/rl_fun/racing/tracks/*.json (centerline, metres). */\nwindow.LAB_TRACKS = ${JSON.stringify(tracks)};\n`,
);
console.log(`icons: ${ICONS.length}, tracks: ${Object.keys(tracks).join(', ')}`);
